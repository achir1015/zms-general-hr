def spoken(sec) -> str:
    """把一節內容轉成朗讀用的文字（表格只朗讀一句提示）。"""
    nums = "一二三四五六七八九十"
    out = [sec["title"] + "。"]
    for b in sec["blocks"]:
        kind = b[0]
        if kind in ("p", "tip"):
            out.append(("提醒：" if kind == "tip" else "") + b[1])
        elif kind == "steps":
            out += ["第%s，%s" % (nums[i] if i < 10 else str(i + 1), s) for i, s in enumerate(b[1])]
        elif kind == "check":
            out += [s + "。" for s in b[1]]
        elif kind == "table":
            out.append("詳細內容請參考畫面上的表格。")
    text = "".join(x if x.endswith(("。", "：", "？")) else x + "。" for x in out)
    return (text.replace("／", "或").replace("→", "到").replace("～", "到").replace("＋", "加").replace("－", "減")
            .replace("＠", "每單位").replace("＝", "等於").replace("×", "乘以").replace("÷", "除以"))
